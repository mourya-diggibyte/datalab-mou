# classification.json (machine-readable summary)
# ---------------------------------------------------------------------------


def emit_classification_json(
    ctx: model.Context,
    decisions: dict[str, classify.TableDecision],
    graph: depgraph.DependencyGraph,
    domain: str,
    out: Path,
    generated_at: datetime | None = None,
) -> Path:
    """Write ``projects/<domain>/classification.json`` with per-table decisions + dep order."""
    target = out / "classification.json"
    target.parent.mkdir(parents=True, exist_ok=True)

    if generated_at is None:
        generated_at = datetime.now(UTC)

    tables_out = {}
    for table_key, td in decisions.items():
        tool_decisions = []
        for tool_d in td.tool_decisions:
            tool_decisions.append(
                {
                    "tool_id": tool_d.tool_id,
                    "name": tool_d.name,
                    "bucket": str(tool_d.bucket),
                    "confidence": str(tool_d.confidence),
                    "score": tool_d.score,
                    "reason": tool_d.reason,
                    "construct": tool_d.construct,
                }
            )
        tables_out[table_key] = {
            "layer": td.layer,
            "confidence": str(td.confidence),
            "needs_transform": td.needs_transform,
            "gaps": [str(g.tool_id) for g in td.gaps],
            "dropped": [str(d.tool_id) for d in td.dropped],
            "review_notes": list(td.review_notes),
            "tool_decisions": tool_decisions,
        }

    data = {
        "generated_at": generated_at.isoformat(),
        "workflow": ctx.workflow,
        "sha256": ctx.sha256,
        "domain": domain,
        "dependency_order": list(graph.order),
        "fan_in": {k: list(v) for k, v in graph.fan_in.items()},
        "fan_out": {k: list(v) for k, v in graph.fan_out.items()},
        "tables": tables_out,
    }

    target.write_text(json.dumps(data, indent=2), encoding="utf-8")
    return target


