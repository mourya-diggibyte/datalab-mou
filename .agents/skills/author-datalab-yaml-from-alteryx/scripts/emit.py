def emit_domain_yml(
    domain: str,
    out: Path,
    catalog_conf: str = "datalab.catalog",
    imports: list[str] | None = None,
) -> Path:
    """Write ``projects/<domain>/config/<domain>/domain.yml``.

    ``imports`` is populated later (Task 7) once transform stubs are emitted; an empty list
    is written here so the file is valid and diffable.  The relative schema depth is 4
    (``projects/<domain>/config/<domain>/domain.yml`` → repo root).
    """
    target = out / "config" / domain / "domain.yml"
    target.parent.mkdir(parents=True, exist_ok=True)

    imports_block = ""
    if imports:
        lines = "\n".join(f"  - {imp}" for imp in imports)
        imports_block = f"imports:\n{lines}\n"
    else:
        imports_block = "imports: []  # populated by emit_transform_stubs (Task 7)\n"

    parts = [
        _schema_header(4, _SCHEMA_DOMAIN),
        "#",
        f"# Domain: {domain}",
        "# Generated by author-datalab-yaml-from-alteryx — review before use.",
        "schema_version: 1",
        f"domain: {domain}",
        imports_block.rstrip(),
        "",
        f"catalog_conf: {catalog_conf}",
        "layers:",
        "  bronze:",
        "    schema_conf: datalab.bronze_schema",
        "    table_properties:",
        "      datalab.layer: bronze",
        "  silver:",
        "    schema_conf: datalab.silver_schema",
        "    table_properties:",
        "      datalab.layer: silver",
        "  gold:",
        "    schema_conf: datalab.gold_schema",
        "    table_properties:",
        "      datalab.layer: gold",
        "",
    ]
    content = "\n".join(parts)

    _assert_no_literal_catalog(content)
    target.write_text(content, encoding="utf-8")
    return target


