def _source_for_table(ctx: model.Context, table_key: str) -> model.Source | None:
    """Return the Source entry whose table_key matches the given key."""
    return ctx.source(table_key)


def emit_bronze_yml(
    ctx: model.Context,
    domain: str,
    source_key: str,
    out: Path,
    catalog_conf: str = "datalab.catalog",
) -> Path:
    """Write ``projects/<domain>/config/<domain>/bronze/<source_key>.yml``.

    Bronze is ingestion-only: no column mapping, ``streaming_table`` target, conf-keyed path.
    If the source's Alteryx tool is a macro that was missing, annotate with ``# MISSING MACRO``.

    Relative schema depth for ``<domain>/bronze/<table>.yml`` from repo root:
    ``projects/<domain>/config/<domain>/bronze/<table>.yml`` → 5 levels up.
    """
    source = _source_for_table(ctx, source_key)
    target = out / "config" / domain / "bronze" / f"{source_key}.yml"
    target.parent.mkdir(parents=True, exist_ok=True)

    # Detect missing-macro situation: if the workflow's macros_missing list is non-empty
    # AND the source tool id matches one that used a missing macro.
    macro_note = ""
    if ctx.macros_missing:
        macro_note = (
            f"# CONFIDENCE: low — MISSING MACRO(S): {', '.join(ctx.macros_missing)}\n"
            "# The source connector requires a macro that was not found during conversion.\n"
            "# Review the source path and format below before running.\n"
        )

    # The source_tables entry (the raw file path / sheet name from Alteryx) is useful context.
    source_tables_comment = ""
    if source and source.source_tables:
        tables_str = ", ".join(f'"{t}"' for t in source.source_tables)
        source_tables_comment = (
            f"# Alteryx source file(s): {tables_str}\n"
            "# Replace path_conf with the actual landing volume conf key for your environment.\n"
        )

    # Pick source kind: Excel/CSV/Sheets-style sources use `files` (batch) or `cloud_files`
    # (streaming Auto Loader). We default to `cloud_files` for streaming_table consistency;
    # a reviewer can downgrade to `files` if the landing path is a one-off batch.
    kind = "cloud_files"
    format_hint = "csv"  # placeholder — reviewer sets the real format

    # If source tables include .xlsx hint, adjust comment
    if source and any(".xlsx" in (st or "").lower() for st in source.source_tables):
        format_hint = "csv  # Alteryx source was .xlsx — convert to CSV/Parquet for Auto Loader"

    confidence_comment = (
        f"# CONFIDENCE: low — source connector macro missing "
        f"({', '.join(ctx.macros_missing) if ctx.macros_missing else 'unknown'})\n"
        if ctx.macros_missing
        else "# CONFIDENCE: medium — source wiring inferred from Alteryx source tool\n"
    )

    header = _schema_header(5, _SCHEMA_TABLE)
    parts = [
        header,
        "#",
        f"# Target table: bronze.{source_key}",
        "# Generated by author-datalab-yaml-from-alteryx — review before use.",
    ]
    if macro_note:
        parts.append(macro_note.rstrip())
    if source_tables_comment:
        parts.append(source_tables_comment.rstrip())
    if confidence_comment:
        parts.append(confidence_comment.rstrip())
    parts += [
        "",
        "schema_version: 1",
        f"name: {source_key}",
        f'comment: "Raw ingestion of {source_key} — schema preserved, no column mapping at bronze."',
        "source:",
        f"  kind: {kind}",
        f"  path_conf: datalab.{source_key}_landing_path"
        "  # FIXME: set the correct landing path conf key",
        f"  format: {format_hint}",
        "  options:",
        '    cloudFiles.inferColumnTypes: "true"',
        "    cloudFiles.schemaEvolutionMode: addNewColumns",
        "  add_lineage: true  # framework adds _ingest_ts + _source_file",
        "target:",
        "  kind: streaming_table",
        "",
    ]
    content = "\n".join(parts)

    _assert_no_literal_catalog(content)
    target.write_text(content, encoding="utf-8")
    return target


