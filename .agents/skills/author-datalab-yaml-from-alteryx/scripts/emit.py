"""Emit datalab YAML artifacts from classified Alteryx-migration output.

One function per artifact type:

- :func:`emit_domain_yml`  — domain.yml skeleton (catalog/schema conf keys, layer defs,
  empty ``imports:`` list populated later by :func:`emit_transform_stubs`).
- :func:`emit_bronze_yml`  — ``files``/``cloud_files`` source + ``streaming_table`` target;
  a ``# MISSING MACRO`` note if the source tool has missing macros.
- :func:`emit_silver_yml`  — ``columns:`` (Select) + ``quality:`` (Filter/null) + optional
  ``transform:`` + ``target.cdc`` (SCD1/SCD2 when a key+order exists).
- :func:`emit_gold_yml`    — ``source.kind: table`` + ``transform:`` + ``materialized_view``.
- :func:`emit_transform_stubs`` — one ``@transform`` stub per transform-needing table,
  carrying the generated PySpark as a starting point + ``# TODO review``.
- :func:`emit_review_file``     — the human-facing ``migration_review.md`` hand-off.

This module WRITES files. It never classifies (``classify.py``) or calls an LLM
(``llm_gaps.py``). Every emitter receives a fully-classified :class:`TableDecision` and the
full :class:`Context` so it can pull the raw PySpark code and source details.

Self-check enforced by :func:`_assert_no_literal_catalog`:
  No emitted YAML may contain a literal ``catalog.schema`` path; all locations must be conf
  keys (``catalog_conf``, ``schema_conf``) resolved per environment.
"""

