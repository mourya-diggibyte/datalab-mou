_SCHEMA_TABLE = "schemas/table_config.schema.json"
_SCHEMA_DOMAIN = "schemas/domain_config.schema.json"


def _schema_header(depth: int, schema: str) -> str:
    """Return the yaml-language-server comment with the correct relative path.

    ``depth`` is the number of ``../`` steps from the emitted file back to the repo root.
    E.g. ``projects/<domain>/config/<domain>/bronze/<table>.yml`` has depth 5.
    """
    prefix = "../" * depth
    return f"# yaml-language-server: $schema={prefix}{schema}"


def _assert_no_literal_catalog(text: str) -> None:
    """Fail fast if the text contains a literal catalog.schema path (e.g. ``prod_catalog.bronze``).

    The heuristic: a dot-separated identifier where NEITHER part is a known YAML key or
    a pure number is suspicious. We check for the most common mistake: any word followed
    by a dot followed by ``bronze``/``silver``/``gold`` that is NOT preceded by ``layer:``.
    """
    import re

    # Catches ``my_catalog.bronze_schema``, ``uc.gold``, etc. but not ``layer: bronze``
    pattern = r'(?<!layer: )\b\w+\.(bronze|silver|gold)\b'
    match = re.search(pattern, text)
    if match:
        raise ValueError(
            f"Emitted YAML contains a literal catalog path '{match.group()}'; "
            "use catalog_conf / schema_conf keys instead."
        )


