        "| Field | Value |",
        "|---|---|",
        f"| Workflow | `{ctx.workflow}` |",
        f"| SHA-256 | `{ctx.sha256[:12]}…` |",
        f"| Domain | `{domain}` |",
        f"| Generated | {generated_at.strftime('%Y-%m-%d %H:%M UTC')} |",
        f"| Tables | {len(ctx.tables)} |",
        f"| Sources | {len(ctx.sources)} |",
