"""Regenerate/verify the vendored editor schemas from the PINNED framework.

The JSON schemas under schemas/ power editor validation through the
yaml-language-server header comment in every config file:

    config/<domain>/domain.yml              -> domain_config.schema.json
    config/<domain>/<layer>/<table>.yml     -> table_config.schema.json
    config/<domain>/templates/<name>.yml    -> template_config.schema.json
    config/<domain>/<layer>/<file>.yml
    carrying a `template:` key              -> template_instance.schema.json

They are generated FROM the datalab Pydantic models — historically by hand-copying
the datalab-framework repo's `make schema` output, which drifted silently on
framework bumps. This script removes the hand step: it imports the SAME four
models from the `datalab` package installed in .venv (i.e. exactly the version
pyproject.toml pins) and emits schemas byte-identically to the framework's
`scripts/export_config_schema.py` (json.dumps(model_json_schema(), indent=2,
sort_keys=True) + newline). If the framework repo adds a fifth schema, add it to
EXPORTS here in the same bump.

    make sync-schemas    # uv run python scripts/sync_schemas.py --write
    make check-schemas   # uv run python scripts/sync_schemas.py --check  (CI + pre-commit)

`--write` regenerates schemas/ from the installed framework (run after every
framework bump — `make bump-framework` does). `--check` asserts the vendored
files match what the pinned framework generates and exits non-zero listing the
drift otherwise.
"""

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = REPO_ROOT / "schemas"


def _exports() -> dict[str, object]:
    # Imported lazily so `--help` works without the venv.
    from datalab.framework.models import (
        DomainConfig,
        TableFile,
        TemplateFile,
        TemplateInstanceFile,
    )

    return {
        "domain_config.schema.json": DomainConfig,
        "table_config.schema.json": TableFile,
        "template_config.schema.json": TemplateFile,
        "template_instance.schema.json": TemplateInstanceFile,
    }


def _render(model: object) -> str:
    return json.dumps(model.model_json_schema(), indent=2, sort_keys=True) + "\n"


def check() -> list[str]:
    """Return drift messages; an empty list means schemas/ matches the pin."""
    problems: list[str] = []
    exports = _exports()
    for filename, model in exports.items():
        vendored = OUT_DIR / filename
        if not vendored.is_file():
            problems.append(f"schemas/{filename} is missing")
            continue
        if vendored.read_text() != _render(model):
            problems.append(f"schemas/{filename} differs from the pinned framework's models")
    expected = set(exports)
    for extra in sorted(p.name for p in OUT_DIR.glob("*.json") if p.name not in expected):
        problems.append(f"schemas/{extra} is not generated by the framework (stale leftover?)")
    return problems


def write() -> None:
    OUT_DIR.mkdir(exist_ok=True)
    for filename, model in _exports().items():
        (OUT_DIR / filename).write_text(_render(model))
        print(f"wrote schemas/{filename}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Sync vendored config schemas with the pinned framework.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate schemas/ from the installed framework")
    mode.add_argument("--check", action="store_true", help="check schemas/ for drift against the installed framework")
    args = parser.parse_args(argv)

    if args.write:
        write()
        return 0

    problems = check()
    if problems:
        print("vendored schemas/ are OUT OF SYNC with the pinned datalab framework:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        print("\nrun `make sync-schemas` to regenerate them.", file=sys.stderr)
        return 1
    print("vendored schemas/ match the pinned datalab framework")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
