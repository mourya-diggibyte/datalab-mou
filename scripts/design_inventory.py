#!/usr/bin/env python3
"""Render design/PIPELINES.md — the pipeline inventory — from the config/ artifacts.

The design package goes stale the moment a table is added and nobody redraws the
diagram. This page cannot: it is RENDERED from the same YAML the framework
generates the pipeline from — one section per domain, with a lineage graph
(mermaid, rendered natively by GitHub) and a table listing every target table,
where its rows come from, what kind of dataset it is and its data-quality gate.

    make design         # --write: re-render design/PIPELINES.md
    make check-design   # --check: fail (CI) while it is stale

Discovery follows the framework loader: a domain is a directory holding
`domain.yml`; its layers are the `layers:` keys that exist as sub-directories,
in declared order; each layer file is one table, or a template INSTANCE
(`template:` + `parameter_sets:`) expanded against `templates/<name>.yml`.
Both repo layouts are found — `config/<domain>/` (adopters) and
`projects/*/config/<domain>/` (the template).

This is a best-effort READER, not a validator: `make validate-configs` owns
correctness. SQL sources are scanned for `FROM`/`JOIN` identifiers to draw their
edges. Needs pyyaml (present in the dev venv); `render()` itself is pure, so the
adopter scaffold can pre-render a repo it has not installed yet.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = Path("design") / "PIPELINES.md"

HEADER = (
    "<!-- GENERATED by scripts/design_inventory.py (`make design`) from the config/ "
    "artifacts — do not edit by hand; `make check-design` (CI) fails while it is stale. -->"
)

PARAM_RE = re.compile(r"\$\{param\.([A-Za-z_][A-Za-z0-9_]*)\}")
# FROM/JOIN targets in a `sql` source: a short dataset name, a dotted name, or a
# ${conf:<key>}-qualified name. Subqueries / CTE names are filtered afterwards.
SQL_REF_RE = re.compile(
    r"\b(?:FROM|JOIN)\s+((?:\$\{conf:[^}]+\}|[A-Za-z_][\w]*)(?:\.[A-Za-z_][\w]*)*)",
    re.IGNORECASE,
)
SQL_CTE_RE = re.compile(r"\b([A-Za-z_]\w*)\s+AS\s*\(", re.IGNORECASE)


@dataclass
class Edge:
    source: str  # node id
    label: str
    dashed: bool = False
    display: str = ""  # node label if the source is not a table of this domain


@dataclass
class Table:
    layer: str
    name: str
    built_from: str
    target: str
    gate: str
    transforms: list[str]
    config: str  # repo-relative path of the artifact
    edges: list[Edge] = field(default_factory=list)
    quarantine: str | None = None
    extra_outputs: list[str] = field(default_factory=list)  # dq metrics / summary


@dataclass
class Domain:
    name: str
    config_dir: str  # repo-relative
    layers: list[str]
    tables: list[Table] = field(default_factory=list)
    # external source nodes: id -> label (landing volumes, Kafka, functions …)
    externals: dict[str, str] = field(default_factory=dict)


# --------------------------------------------------------------------------- #
# Analysis — a table spec (already-parsed dict) -> Table
# --------------------------------------------------------------------------- #

def node_id(*parts: str) -> str:
    return "__".join(re.sub(r"\W", "_", p) for p in parts)


def table_node(domain: str, layer: str, name: str) -> str:
    return node_id(domain, layer, name)


def _code(text: str) -> str:
    return f"`{text}`"


def _steps(spec: dict) -> list[dict]:
    steps = spec.get("transform") or []
    return [steps] if isinstance(steps, dict) else list(steps)


def _rules(spec: dict) -> list[dict]:
    rules: list[dict] = []
    for column in spec.get("columns") or []:
        rules.extend(column.get("quality") or [])
    quality = spec.get("quality") or {}
    rules.extend(quality.get("checks") or [])
    return rules


class Analyzer:
    """Turns table specs into Tables, resolving references within one domain.

    `known` lists every (layer, name) the domain declares, so SHORT-name
    references (sql / view sources) resolve regardless of file order."""

    def __init__(self, domain: Domain, known: list[tuple[str, str]]):
        self.domain = domain
        self.known = known

    def _external(self, key: str, label: str) -> str:
        nid = node_id(self.domain.name, "src", key)
        self.domain.externals.setdefault(nid, label)
        return nid

    def _table_ref(self, ref: dict, own_layer: str) -> tuple[str, str]:
        """(node id, plain display) for a {name, layer?, schema_conf?, catalog_conf?}
        ref. The layer defaults to the reading table's own (framework rule)."""
        name = ref.get("name", "?")
        if ref.get("catalog_conf") or ref.get("schema_conf"):
            where = ".".join(
                f"${{{ref[k]}}}" for k in ("catalog_conf", "schema_conf") if ref.get(k)
            )
            display = f"{where}.{name}"
            return self._external(f"ext_{where}_{name}", display), display
        layer = ref.get("layer") or own_layer
        return table_node(self.domain.name, layer, name), f"{layer}.{name}"

    def _short_name(self, name: str, own_layer: str) -> str | None:
        """Resolve a same-pipeline dataset referenced by SHORT name (sql/view)."""
        layers = [layer for layer, known in self.known if known == name]
        if not layers:
            return None
        layer = own_layer if own_layer in layers else layers[0]
        return table_node(self.domain.name, layer, name)

    def _source(self, source: dict, own_layer: str, flow: str = "") -> tuple[str, list[Edge]]:
        kind = source.get("kind", "?")
        tag = f"{flow}: " if flow else ""
        if kind in ("cloud_files", "files"):
            fmt = source.get("format") or ("json" if kind == "cloud_files" else "parquet")
            conf = source.get("path_conf", "?")
            what = "Auto Loader" if kind == "cloud_files" else "files"
            nid = self._external(f"{kind}_{conf}", f"{what} · {conf}")
            return f"{tag}{what} ({fmt}) · {_code(conf)}", [Edge(nid, what)]
        if kind == "table":
            nid, display = self._table_ref(source, own_layer)
            mode = []
            if source.get("as_stream"):
                mode.append("stream")
            if source.get("change_data_feed"):
                mode.append("change feed")
            suffix = f" ({', '.join(mode)})" if mode else ""
            edge = Edge(nid, ", ".join(mode) or "read", display=display)
            return f"{tag}{_code(display)}{suffix}", [edge]
        if kind == "view":
            name = source.get("name", "?")
            nid = self._short_name(name, own_layer) or self._external(f"view_{name}", f"view {name}")
            return f"{tag}view {_code(name)}", [Edge(nid, "view")]
        if kind == "kafka":
            topic = source.get("topic") or source.get("subscribe_pattern") or "?"
            nid = self._external(f"kafka_{topic}", f"Kafka · {topic}")
            return f"{tag}Kafka · {_code(topic)}", [Edge(nid, "Kafka")]
        if kind == "sql":
            query = source.get("query", "")
            ctes = {m.lower() for m in SQL_CTE_RE.findall(query)}
            refs = []
            for ref in SQL_REF_RE.findall(query):
                if ref.lower() in ctes or ref in refs:
                    continue
                refs.append(ref)
            edges = []
            for ref in refs:
                nid = None if "." in ref else self._short_name(ref, own_layer)
                edges.append(Edge(nid or self._external(f"sql_{ref}", ref), "sql"))
            shown = ", ".join(_code(r) for r in refs) or "a query"
            return f"{tag}SQL over {shown}", edges
        if kind in ("snapshot_function", "python"):
            fn = source.get("function", "?")
            nid = self._external(f"fn_{fn}", f"{kind} · {fn}")
            return f"{tag}{kind.replace('_', ' ')} {_code(fn)}", [Edge(nid, kind.replace("_", " "))]
        nid = self._external(f"kind_{kind}", kind)
        return f"{tag}{kind}", [Edge(nid, kind)]

    def table(self, spec: dict, layer: str, config: str) -> Table:
        name = spec.get("name", "?")
        target = spec.get("target") or {}
        built: list[str] = []
        edges: list[Edge] = []
        if spec.get("source"):
            text, es = self._source(spec["source"], layer)
            built.append(text)
            edges.extend(es)
        for flow in spec.get("sources") or []:
            text, es = self._source(flow.get("source") or {}, layer, flow.get("name", ""))
            built.append(text)
            edges.extend(es)
        for flow in spec.get("backfill") or []:
            text, es = self._source(flow.get("source") or {}, layer, flow.get("name", ""))
            built.append(f"backfill {text}")
            edges.extend(Edge(e.source, "backfill", True, e.display) for e in es)

        transforms: list[str] = []
        for step in _steps(spec):
            if step.get("function"):
                transforms.append(step["function"])
            for ref in (step.get("tables") or {}).values():
                nid, display = self._table_ref(ref, layer)
                edges.append(Edge(nid, "lookup", dashed=True, display=display))
                built.append(f"lookup {_code(display)}")
        quality = spec.get("quality") or {}
        for ref in (quality.get("references") or {}).values():
            nid, display = self._table_ref(ref, layer)
            edges.append(Edge(nid, "dq lookup", dashed=True, display=display))

        # target kind
        kind = target.get("kind", "?")
        if kind == "streaming_table":
            desc = "streaming table"
            if target.get("cdc"):
                cdc = target["cdc"]
                keys = ", ".join(cdc.get("keys") or [])
                desc += f" · AUTO CDC SCD{cdc.get('scd_type', 1)} on {_code(keys)}"
            if target.get("cdc_from_snapshot"):
                snap = target["cdc_from_snapshot"]
                keys = ", ".join(snap.get("keys") or [])
                desc += f" · snapshot CDC SCD{snap.get('scd_type', 1)} on {_code(keys)}"
        elif kind == "materialized_view":
            desc = "materialized view"
            if target.get("refresh_policy"):
                desc += f" · refresh {target['refresh_policy']}"
        elif kind == "temporary_view":
            desc = "temporary view (pipeline-scoped)"
        elif kind == "delta_sink":
            desc = f"Delta sink → {_code(target.get('table_conf') or target.get('path_conf') or '?')}"
        elif kind == "kafka_sink":
            desc = f"Kafka sink → {_code(target.get('topic') or 'per-row topic')}"
        elif kind == "foreach_batch_sink":
            desc = f"foreachBatch sink {_code(target.get('function', '?'))}"
        else:
            desc = kind

        # quality gate — criticality defaults to error (framework model)
        rules = _rules(spec)
        errors = sum(1 for r in rules if (r.get("criticality") or "error") == "error")
        warns = len(rules) - errors
        quarantine = None
        q_cfg = quality.get("quarantine") or {}
        if errors and q_cfg.get("enabled", True) and kind != "temporary_view":
            quarantine = q_cfg.get("name") or f"{name}_quarantine"
        parts = []
        if errors:
            parts.append(f"{errors} error" + (f" → {_code(quarantine)}" if quarantine else ""))
        if warns:
            parts.append(f"{warns} warn")
        extra: list[str] = []
        metrics = quality.get("metrics") or {}
        if metrics.get("enabled"):
            extra.append(metrics.get("name") or f"{name}_dq_metrics")
            if metrics.get("summary"):
                extra.append(f"{name}_dq_summary")
            parts.append("metrics " + ", ".join(_code(x) for x in extra))

        return Table(
            layer=layer,
            name=name,
            built_from="; ".join(built) or "—",
            target=desc,
            gate=" · ".join(parts) or "—",
            transforms=transforms,
            config=config,
            edges=edges,
            quarantine=quarantine,
            extra_outputs=extra,
        )


def analyze(domain: Domain, specs: list[tuple[str, dict, str]]) -> Domain:
    """Fill `domain.tables` from (layer, spec, config path) triples. Shared by
    discover() and the adopter scaffold (which pre-renders its starter table)."""
    analyzer = Analyzer(domain, [(layer, spec.get("name", "?")) for layer, spec, _ in specs])
    domain.tables = [analyzer.table(spec, layer, rel) for layer, spec, rel in specs]
    declared = {table_node(domain.name, t.layer, t.name) for t in domain.tables}
    for table in domain.tables:
        for edge in table.edges:
            if edge.source not in declared and edge.source not in domain.externals:
                # pre-existing / another pipeline's table: draw it as a source
                domain.externals[edge.source] = edge.display or edge.source
    return domain


# --------------------------------------------------------------------------- #
# Discovery (YAML)
# --------------------------------------------------------------------------- #

def _load_yaml(path: Path):
    import yaml  # dev-venv dependency; imported lazily so render() stays pure

    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def _substitute(node, params: dict):
    if isinstance(node, str):
        whole = PARAM_RE.fullmatch(node)
        if whole:
            return params.get(whole.group(1), node)
        return PARAM_RE.sub(lambda m: str(params.get(m.group(1), m.group(0))), node)
    if isinstance(node, list):
        return [_substitute(item, params) for item in node]
    if isinstance(node, dict):
        return {key: _substitute(value, params) for key, value in node.items()}
    return node


def _expand_instance(instance: dict, domain_dir: Path) -> list[dict]:
    name = instance.get("template", "")
    for ext in ("yml", "yaml"):
        path = domain_dir / "templates" / f"{name}.{ext}"
        if path.exists():
            break
    else:
        return []
    template = _load_yaml(path)
    defaults = {
        p["name"]: p["default"] for p in template.get("parameters") or [] if "default" in p
    }
    return [
        _substitute(template.get("spec") or {}, {**defaults, **params})
        for params in instance.get("parameter_sets") or []
    ]


def discover(root: Path) -> list[Domain]:
    domain_files = sorted(
        [*root.glob("config/*/domain.y*ml"), *root.glob("projects/*/config/*/domain.y*ml")]
    )
    domains: list[Domain] = []
    for domain_file in domain_files:
        domain_dir = domain_file.parent
        meta = _load_yaml(domain_file)
        layers = [lay for lay in (meta.get("layers") or {}) if (domain_dir / lay).is_dir()]
        domain = Domain(
            name=str(meta.get("domain") or domain_dir.name),
            config_dir=domain_dir.relative_to(root).as_posix(),
            layers=layers,
        )
        # First pass: every spec + its layer, so short-name refs (sql / view)
        # resolve regardless of file order.
        specs: list[tuple[str, dict, str]] = []
        for layer in layers:
            files = sorted((domain_dir / layer).glob("*.yml")) + sorted(
                (domain_dir / layer).glob("*.yaml")
            )
            for path in files:
                data = _load_yaml(path)
                rel = path.relative_to(root).as_posix()
                batch = _expand_instance(data, domain_dir) if data.get("template") else [data]
                specs.extend((layer, spec, rel) for spec in batch)
        domains.append(analyze(domain, specs))
    return domains


# --------------------------------------------------------------------------- #
# Rendering (pure)
# --------------------------------------------------------------------------- #

def _label(text: str) -> str:
    return text.replace('"', "#quot;")


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_domain(domain: Domain, link_prefix: str) -> str:
    lines = [f"## `{domain.name}` — `{domain.config_dir}/`", ""]
    if not domain.tables:
        return "\n".join([*lines, "_No tables yet._", ""])
    mermaid = ["```mermaid", "flowchart LR"]
    for nid, label in domain.externals.items():
        mermaid.append(f'  {nid}["{_label(label)}"]:::source')
    for layer in domain.layers:
        members = [t for t in domain.tables if t.layer == layer]
        if not members:
            continue
        mermaid.append(f'  subgraph {node_id(domain.name, "layer", layer)}["{layer}"]')
        for t in members:
            kind = t.target.split(" · ")[0].split(" → ")[0]
            mermaid.append(
                f'    {table_node(domain.name, t.layer, t.name)}["{_label(t.name)}<br/>{_label(kind)}"]'
            )
            if t.quarantine:
                qid = node_id(domain.name, t.layer, t.quarantine)
                mermaid.append(f'    {qid}["{_label(t.quarantine)}"]:::quarantine')
        mermaid.append("  end")
    for t in domain.tables:
        target = table_node(domain.name, t.layer, t.name)
        for edge in t.edges:
            arrow = "-.->" if edge.dashed else "-->"
            mermaid.append(f'  {edge.source} {arrow}|"{_label(edge.label)}"| {target}')
        if t.quarantine:
            qid = node_id(domain.name, t.layer, t.quarantine)
            mermaid.append(f'  {target} -.->|"dqx error rows"| {qid}')
    mermaid.append("  classDef source fill:#eef4ff,stroke:#3366bb,color:#000")
    mermaid.append("  classDef quarantine fill:#f8cecc,stroke:#c0392b,color:#000")
    mermaid.append("```")

    table = [
        "| Layer | Table | Built from | Target | Quality gate | Transforms | Config |",
        "|---|---|---|---|---|---|---|",
    ]
    for t in domain.tables:
        transforms = ", ".join(_code(fn) for fn in t.transforms) or "—"
        rel = t.config.removeprefix(domain.config_dir + "/")
        cells = [t.layer, _code(t.name), t.built_from, t.target, t.gate, transforms]
        table.append(
            "| " + " | ".join(_cell(c) for c in cells)
            + f" | [{_code(rel)}]({link_prefix}{t.config}) |"
        )
    return "\n".join([*lines, *mermaid, "", *table, ""])


def render(domains: list[Domain], link_prefix: str = "../") -> str:
    """The whole page. `link_prefix` is the path from design/ to the repo root."""
    body = [
        HEADER,
        "",
        "# Pipeline inventory",
        "",
        "Every target table the `config/` artifacts declare, per domain: where its",
        "rows come from, what kind of dataset it is and its data-quality gate. Solid",
        "arrows are reads, dashed arrows are lookups/backfills, red nodes are dqx",
        "quarantine tables. Regenerate with `make design` after adding or changing a",
        "table — CI's `make check-design` fails while this page is stale.",
        "",
    ]
    if not domains:
        body += ["_No domains found (no `config/<domain>/domain.yml`)._", ""]
    for domain in domains:
        body.append(render_domain(domain, link_prefix))
    return "\n".join(body).rstrip() + "\n"


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="re-render design/PIPELINES.md")
    mode.add_argument("--check", action="store_true", help="fail if design/PIPELINES.md is stale")
    parser.add_argument("--root", default=str(REPO_ROOT), help="repo root (default: this repo)")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    out = root / OUTPUT
    rendered = render(discover(root))
    if args.write:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUTPUT}")
        return 0
    current = out.read_text(encoding="utf-8") if out.exists() else ""
    if current == rendered:
        print(f"{OUTPUT} is current with the config/ artifacts")
        return 0
    diff = "\n".join(
        difflib.unified_diff(
            current.splitlines(), rendered.splitlines(), f"{OUTPUT} (committed)",
            f"{OUTPUT} (rendered from config/)", lineterm="", n=1,
        )
    )
    print(
        f"{OUTPUT} is STALE — a table was added or changed without re-rendering the "
        f"design. Run `make design` and commit the result.\n\n{diff}",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
